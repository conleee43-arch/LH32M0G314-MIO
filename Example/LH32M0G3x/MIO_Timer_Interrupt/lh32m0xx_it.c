void MIO_IRQHandler(void)
{
    LHL_MIO_ClearPending(MIO_TIMER0_IT_FLAG_TSF);
    
    LHL_GPIO_TogglePin(pGPIO0, GPIO_PIN_4);         // 翻转P0.4    
}

